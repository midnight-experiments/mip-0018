// Generates the equivalence-test contracts: the same payload shapes built with the default typed
// module and with the pure-circuit alternative. Shapes:
//   * one record per value size V = 1..219 (key size chosen so every record fits; V = 219 has the
//     1-byte key of the MIP's capacity limit), cycling through value types bytes / UTF-8 / JSON / URI;
//   * MULTI random multi-record shapes (2-4 records, uint8 / uint128 / Null records included).
// Circuit arguments are (domainSep, kind, key1, value1, ...); uint values are numbers, Null records
// have no value argument.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

export type RecordKind = 'bytes' | 'utf8' | 'json' | 'uri' | 'uint8' | 'uint128' | 'null';
export type RecordShape = { kind: RecordKind; k: number; v: number };
export type Shape = { name: string; records: RecordShape[] };

/** Deterministic PRNG (mulberry32). */
export const prng = (seed: number) => {
  let a = seed >>> 0;
  return (): number => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

const VALUE_KINDS: RecordKind[] = ['bytes', 'utf8', 'json', 'uri'];

export const MULTI = 24;

export const shapes = (): Shape[] => {
  const out: Shape[] = [];
  for (let v = 1; v <= 219; v++) {
    const k = 1 + ((v * 37) % (220 - v));
    let kind = VALUE_KINDS[v % 4]!;
    if (kind === 'uri' && v < 3) kind = 'bytes';
    out.push({ name: `v${v}`, records: [{ kind, k, v }] });
  }
  const rnd = prng(0x0018_0018);
  const int = (lo: number, hi: number) => lo + Math.floor(rnd() * (hi - lo + 1));
  const kinds: RecordKind[] = ['bytes', 'utf8', 'json', 'uri', 'uint8', 'uint128', 'null'];
  const valueSize = (kind: RecordKind): number => {
    if (kind === 'uint8') return 1;
    if (kind === 'uint128') return 16;
    if (kind === 'null') return 0;
    return int(kind === 'uri' ? 3 : kind === 'json' ? 1 : 0, 70);
  };
  for (let i = 0; i < MULTI; i++) {
    const n = int(2, 4);
    for (;;) {
      const records = Array.from({ length: n }, () => {
        const kind = kinds[int(0, kinds.length - 1)]!;
        return { kind, k: int(1, 30), v: valueSize(kind) };
      });
      if (records.reduce((a, r) => a + 3 + r.k + r.v, 0) <= 223) {
        out.push({ name: `m${i}`, records });
        break;
      }
    }
  }
  return out;
};

const typedBuilder: Record<RecordKind, string> = {
  bytes: 'bytesRecord',
  utf8: 'utf8Record',
  json: 'jsonRecord',
  uri: 'uriRecord',
  uint8: 'uintRecord',
  uint128: 'uint128Record',
  null: 'nullRecord',
};

const params = (s: Shape): string[] => {
  const p = ['ds: Bytes<32>', 'kind: Uint<8>'];
  s.records.forEach((r, i) => {
    p.push(`k${i}: Bytes<${r.k}>`);
    if (r.kind === 'uint8') p.push(`v${i}: Uint<8>`);
    else if (r.kind === 'uint128') p.push(`v${i}: Uint<128>`);
    else if (r.kind !== 'null') p.push(`v${i}: Bytes<${r.v}>`);
  });
  return p;
};

const typedRecord = (r: RecordShape, i: number): string => {
  const b = `M_${typedBuilder[r.kind]}`;
  if (r.kind === 'uint8' || r.kind === 'uint128') return `${b}<${r.k}>(k${i}, v${i})`;
  if (r.kind === 'null') return `${b}<${r.k}>(k${i})`;
  return `${b}<${r.k}, ${r.v}>(k${i}, v${i})`;
};

const pureRecord = (r: RecordShape, i: number): string => {
  const b = `P_${typedBuilder[r.kind]}`;
  const size = 3 + r.k + r.v;
  if (r.kind === 'uint8' || r.kind === 'uint128') return `${b}<${r.k}, ${size}>(k${i}, v${i})`;
  if (r.kind === 'null') return `${b}<${r.k}, ${size}>(k${i})`;
  return `${b}<${r.k}, ${r.v}, ${size}>(k${i}, v${i})`;
};

export const typedSource = (all: Shape[]): string =>
  [
    '// GENERATED by packages/compact/test/lib/generate.ts — do not edit.',
    'pragma language_version >= 0.26.0;',
    'import CompactStandardLibrary;',
    'import "../../src/Mip0018" prefix M_;',
    ...all.map((s) => {
      const gens = s.records.flatMap((r) => [r.k, r.v]);
      return `export circuit ${s.name}(${params(s).join(', ')}): [] {\n  M_emitPayload(M_payload${s.records.length}<${gens.join(', ')}>(M_header(ds, kind), ${s.records.map(typedRecord).join(', ')}));\n}`;
    }),
    '',
  ].join('\n');

export const pureSource = (all: Shape[]): string =>
  [
    '// GENERATED by packages/compact/test/lib/generate.ts — do not edit.',
    'pragma language_version >= 0.26.0;',
    'import CompactStandardLibrary;',
    'import "../../src/Mip0018Pure" prefix P_;',
    ...all.map((s) => {
      const sizes = s.records.map((r) => 3 + r.k + r.v);
      const pad = 223 - sizes.reduce((a, b) => a + b, 0);
      return `export circuit ${s.name}(${params(s).join(', ')}): [] {\n  P_emitPayload(P_payload${s.records.length}<${[...sizes, pad].join(', ')}>(P_header(ds, kind), ${s.records.map(pureRecord).join(', ')}));\n}`;
    }),
    '',
  ].join('\n');

/** Writes `content` to `path` only if it changed (keeps the compile cache valid). */
export const writeIfChanged = (path: string, content: string): void => {
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
};
